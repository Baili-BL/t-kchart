/** [x0, y0, x1, y1]，都是 0–1 的分数 */
export type Rect = [number, number, number, number];

export interface LayoutDef {
  /** 稳定 id：`<图数>-<序号>`，如 `4-3` */
  id: string;
  /** 图的张数 */
  count: number;
  /** 同张数里的第几种（从 1 起） */
  variant: number;
  /** 阅读顺序（先上后下、先左后右）；第 i 个矩形就是第 i 格 */
  cells: Rect[];
}

function L(count: number, variant: number, cells: Rect[]): LayoutDef {
  return { id: `${count}-${variant}`, count, variant, cells };
}

