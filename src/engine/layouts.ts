/* ------------------------------------------------------------------ 栅格化 */

const EPS = 1e-6;

/** 把一组坐标去重（容差内视为同一条线）并排序 */
function lines(vals: number[]): number[] {
  const s = [...vals].sort((a, b) => a - b);
  const out: number[] = [];
  for (const v of s) if (!out.length || v - out[out.length - 1] > EPS) out.push(v);
  return out;
}

export interface GridTemplate {
  /** 各列 / 各行的相对宽高（fr） */
  cols: number[];
  rows: number[];
  /** 每格占的轨道，1 起、右 / 下开区间，直接可以写进 `grid-column` / `grid-row` */
  place: { c0: number; c1: number; r0: number; r1: number }[];
}

/** 把任意矩形布局翻译成 CSS Grid 的轨道 + 跨度（以所有边为刻度线） */
export function gridTemplate(def: LayoutDef): GridTemplate {
  const xs = lines(def.cells.flatMap((c) => [c[0], c[2]]));
  const ys = lines(def.cells.flatMap((c) => [c[1], c[3]]));
  const at = (arr: number[], v: number): number => arr.findIndex((a) => Math.abs(a - v) < EPS);
  return {
    cols: xs.slice(1).map((x, i) => x - xs[i]),
    rows: ys.slice(1).map((y, i) => y - ys[i]),
    place: def.cells.map((c) => ({
      c0: at(xs, c[0]) + 1,
      c1: at(xs, c[2]) + 1,
      r0: at(ys, c[1]) + 1,
      r1: at(ys, c[3]) + 1,
    })),
  };
}

/** 若布局恰好是均匀的 rows × cols 网格则返回行列数，否则 null */
export function uniformGrid(def: LayoutDef): { rows: number; cols: number } | null {
  const t = gridTemplate(def);
  const cols = t.cols.length;
  const rows = t.rows.length;
  if (cols * rows !== def.count) return null;
  if (!t.place.every((p) => p.c1 - p.c0 === 1 && p.r1 - p.r0 === 1)) return null;
  const eq = (a: number[]): boolean => a.every((v) => Math.abs(v - a[0]) < EPS);
  return eq(t.cols) && eq(t.rows) ? { rows, cols } : null;
}

/** rows × cols 对应的布局 id；没有这种均匀网格就返回 null */
export function uniformLayoutId(rows: number, cols: number): string | null {
  for (const l of LAYOUTS) {
    const g = uniformGrid(l);
    if (g && g.rows === rows && g.cols === cols) return l.id;
  }
  return null;
}

